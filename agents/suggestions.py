class SuggestionProvider:
    """针对某分区的追问推荐器，只产出本分区内的候选问题。"""

    def __init__(self, zone: str):
        self.zone = zone
        self.pool = _ZONE_SUGGESTIONS.get(zone, {})

    def suggest(self, matched_key: str | None = None, limit: int = 3) -> list[str]:
        candidates = self.pool.get(matched_key) if matched_key else None
        if not candidates:
            candidates = self.pool.get("默认", [])
        return candidates[:limit]


# 供 graph 使用的类型
Provider = Callable[[str | None, int], list[str]]
